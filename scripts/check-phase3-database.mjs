const ROOT = fileURLToPath(new URL("../", import.meta.url)).replace(/[\\/]$/, "");
const EVIDENCE = join(ROOT, "evidence", "phase-3-database-verification.json");
const GENERATED = join(
  ROOT,
  "src",
  "shared",
  "adapters",
  "postgres",
  "database.generated.ts",
);
const CODEGEN = join(ROOT, "node_modules", "kysely-codegen", "dist", "cli", "bin.js");
const TABLES = ["idempotency_records", "jobs", "outbox_events"];
const ROLES = [
  "anon",
  "authenticated",
  "shipwithali_application",
  "shipwithali_worker",
  "shipwithali_migration",
  "shipwithali_backup",
];

function listFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

function migrationFiles() {
  return readdirSync(join(ROOT, "supabase", "migrations"))
    .filter((file) => /^\d{14}_[a-z0-9_]+\.sql$/.test(file))
    .sort();
}

function sourceVerification() {
  const failures = [];
  const migrations = migrationFiles();
  const migrationText = migrations
    .map((file) => readFileSync(join(ROOT, "supabase", "migrations", file), "utf8"))
    .join("\n")
    .toLowerCase();
  for (const table of TABLES) {
    if (!migrationText.includes(`create table operations.${table}`)) {
      failures.push(`missing operations.${table}`);
    }
    if (!migrationText.includes(`alter table operations.${table} force row level security`)) {
      failures.push(`operations.${table} does not force RLS`);
    }
  }
  if (/create\s+(?:unlogged\s+)?table\s+(?:phase3_test|public_read\.__phase3)/i.test(migrationText)) {
    failures.push("production migrations contain disposable fixture objects");
  }
  if (!existsSync(GENERATED) || !readFileSync(GENERATED, "utf8").includes("generated by kysely-codegen")) {
    failures.push("generated database types are missing");
  }

  for (const file of listFiles(join(ROOT, "src")).filter((path) => path.endsWith(".ts"))) {
    const path = relative(ROOT, file).split("\\").join("/");
    const content = readFileSync(file, "utf8");
    const adapter = path.includes("/adapters/") || path === "src/bootstrap/composition-root.ts";
    if (/from\s+["'](?:kysely|pg)["']/.test(content) && !adapter) {
      failures.push(`${path} imports a database provider outside adapters/composition`);
    }
    if (/database\.generated(?:\.js)?["']/.test(content) && !path.includes("/adapters/")) {
      failures.push(`${path} imports generated database types outside adapters`);
    }
    if (/\bAsyncLocalStorage\b/.test(content)) {
      failures.push(`${path} uses hidden ambient transaction state`);
    }
    if (/new\s+(?:Pool|Kysely)\s*\(/.test(content) && !adapter) {
      failures.push(`${path} constructs a database provider outside composition/adapters`);
    }
  }

  return { failures, migrations };
}

async function roleAllows(connectionString, role, statement) {
  if (!ROLES.includes(role)) throw new Error("UNKNOWN_ROLE");
  const client = new Client({ connectionString });
  await client.connect();
  let allowed = false;
  try {
    await client.query("begin");
    await client.query(`set session authorization ${role}`);
    try {
      await client.query(statement);
      allowed = true;
    } catch {
      allowed = false;
    }
    await client.query("rollback");
    await client.query("reset session authorization");
  } finally {
    await client.end();
  }
  return allowed;
}

function collectIndexes(plan) {
  const indexes = [];
  const visit = (node) => {
    if (typeof node?.["Index Name"] === "string") indexes.push(node["Index Name"]);
    for (const child of node?.Plans ?? []) visit(child);
  };
  visit(plan);
  return [...new Set(indexes)].sort();
}

async function localVerification(connectionString) {
  const client = new Client({ connectionString });
  await client.connect();
  let defaultProbeCreated = false;
  let phase = "METADATA";
  try {
    const tables = await client.query(
      `select c.relname, c.relrowsecurity, c.relforcerowsecurity
         from pg_class c join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'operations' and c.relname = any($1::text[])
        order by c.relname`,
      [TABLES],
    );
    if (
      tables.rowCount !== TABLES.length ||
      tables.rows.some((row) => !row.relrowsecurity || !row.relforcerowsecurity)
    ) {
      throw new Error("RLS_MATRIX_INCOMPLETE");
    }

    const policies = await client.query(
      `select tablename, policyname, roles, cmd
         from pg_policies
        where schemaname = 'operations'
        order by tablename, policyname`,
    );
    const expectedPolicies = [
      ["idempotency_records", "idempotency_application_insert_policy", "INSERT", "shipwithali_application"],
      ["idempotency_records", "idempotency_application_select_policy", "SELECT", "shipwithali_application"],
      ["idempotency_records", "idempotency_application_update_policy", "UPDATE", "shipwithali_application"],
      ["idempotency_records", "operations_backup_policy_idempotency", "SELECT", "shipwithali_backup"],
      ["jobs", "jobs_worker_insert_policy", "INSERT", "shipwithali_worker"],
      ["jobs", "jobs_worker_select_policy", "SELECT", "shipwithali_worker"],
      ["jobs", "jobs_worker_update_policy", "UPDATE", "shipwithali_worker"],
      ["jobs", "operations_backup_policy_jobs", "SELECT", "shipwithali_backup"],
      ["outbox_events", "operations_backup_policy_outbox", "SELECT", "shipwithali_backup"],
      ["outbox_events", "outbox_application_insert_policy", "INSERT", "shipwithali_application"],
      ["outbox_events", "outbox_worker_select_policy", "SELECT", "shipwithali_worker"],
      ["outbox_events", "outbox_worker_update_policy", "UPDATE", "shipwithali_worker"],
    ];
    const policyMatches = expectedPolicies.every(([table, policy, command, role]) =>
      policies.rows.some(
        (row) =>
          row.tablename === table &&
          row.policyname === policy &&
          row.cmd === command &&
          String(row.roles) === `{${role}}`,
      ),
    );
    if (policies.rows.length !== expectedPolicies.length || !policyMatches) {
      throw new Error("RLS_POLICIES_INCOMPLETE");
    }

    await client.query("set role shipwithali_migration");
    await client.query("create table operations.__phase3_default_probe (id integer)");
    await client.query("reset role");
    defaultProbeCreated = true;

    phase = "ROLE_MATRIX";
    const idempotencyInsert = `insert into operations.idempotency_records (
      operation_scope, actor_scope, key_hash, request_hash, status, expires_at
    ) values (
      'phase3.role.probe', repeat('a', 64), repeat('b', 64), repeat('c', 64),
      'reserved', transaction_timestamp() + interval '1 day'
    )`;
    const outboxInsert = `insert into operations.outbox_events (
      event_id, event_type, schema_version, aggregate_id, aggregate_version,
      payload, correlation_id, occurred_at, available_at
    ) values (
      '018f4f7d-5000-7000-8000-000000000001', 'phase3.role.probe', 1,
      '018f4f7d-5000-7000-8000-000000000002', 1, '{}'::jsonb,
      'phase3-role-probe', transaction_timestamp(), transaction_timestamp()
    )`;
    const jobInsert = `insert into operations.jobs (
      job_id, job_type, payload_version, payload, available_at
    ) values (
      '018f4f7d-5000-7000-8000-000000000003', 'phase3.role.probe', 1,
      '{}'::jsonb, transaction_timestamp()
    )`;
    const roleMatrix = {
      anonBaseRead: await roleAllows(
        connectionString,
        "anon",
        "select count(*) from operations.outbox_events",
      ),
      authenticatedBaseRead: await roleAllows(
        connectionString,
        "authenticated",
        "select count(*) from operations.outbox_events",
      ),
      applicationIdempotencyRead: await roleAllows(
        connectionString,
        "shipwithali_application",
        "select count(*) from operations.idempotency_records",
      ),
      applicationIdempotencyInsert: await roleAllows(
        connectionString,
        "shipwithali_application",
        idempotencyInsert,
      ),
      applicationIdempotencyUpdate: await roleAllows(
        connectionString,
        "shipwithali_application",
        "update operations.idempotency_records set expires_at = expires_at where operation_scope = 'absent'",
      ),
      applicationIdempotencyDelete: await roleAllows(
        connectionString,
        "shipwithali_application",
        "delete from operations.idempotency_records where false",
      ),
      applicationOutboxInsert: await roleAllows(
        connectionString,
        "shipwithali_application",
        outboxInsert,
      ),
      applicationOutboxRead: await roleAllows(
        connectionString,
        "shipwithali_application",
        "select count(*) from operations.outbox_events",
      ),
      applicationOutboxUpdate: await roleAllows(
        connectionString,
        "shipwithali_application",
        "update operations.outbox_events set available_at = available_at where false",
      ),
      applicationOutboxDelete: await roleAllows(
        connectionString,
        "shipwithali_application",
        "delete from operations.outbox_events where false",
      ),
      applicationJobRead: await roleAllows(
        connectionString,
        "shipwithali_application",
        "select count(*) from operations.jobs",
      ),
      applicationDdl: await roleAllows(
        connectionString,
        "shipwithali_application",
        "create table operations.__forbidden_application_ddl (id integer)",
      ),
      workerJobRead: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "select count(*) from operations.jobs",
      ),
      workerJobInsert: await roleAllows(connectionString, "shipwithali_worker", jobInsert),
      workerJobUpdate: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "update operations.jobs set available_at = available_at where false",
      ),
      workerJobDelete: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "delete from operations.jobs where false",
      ),
      workerOutboxRead: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "select count(*) from operations.outbox_events",
      ),
      workerOutboxInsert: await roleAllows(connectionString, "shipwithali_worker", outboxInsert),
      workerOutboxUpdate: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "update operations.outbox_events set available_at = available_at where false",
      ),
      workerOutboxDelete: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "delete from operations.outbox_events where false",
      ),
      workerIdempotencyRead: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "select count(*) from operations.idempotency_records",
      ),
      backupRead: await roleAllows(
        connectionString,
        "shipwithali_backup",
        "select count(*) from operations.outbox_events",
      ),
      backupWrite: await roleAllows(
        connectionString,
        "shipwithali_backup",
        "delete from operations.outbox_events where false",
      ),
      migrationDdl: await roleAllows(
        connectionString,
        "shipwithali_migration",
        "create table operations.__phase3_migration_role_probe (id integer)",
      ),
      anonBaseWrite: await roleAllows(connectionString, "anon", outboxInsert),
      authenticatedBaseWrite: await roleAllows(connectionString, "authenticated", outboxInsert),
      applicationFutureObjectRead: await roleAllows(
        connectionString,
        "shipwithali_application",
        "select count(*) from operations.__phase3_default_probe",
      ),
      workerFutureObjectRead: await roleAllows(
        connectionString,
        "shipwithali_worker",
        "select count(*) from operations.__phase3_default_probe",
      ),
    };
    const expected = {
      anonBaseRead: false,
      authenticatedBaseRead: false,
      applicationIdempotencyRead: true,
      applicationIdempotencyInsert: true,
      applicationIdempotencyUpdate: true,
      applicationIdempotencyDelete: false,
      applicationOutboxInsert: true,
      applicationOutboxRead: false,
      applicationOutboxUpdate: false,
      applicationOutboxDelete: false,
      applicationJobRead: false,
      applicationDdl: false,
      workerJobRead: true,
      workerJobInsert: true,
      workerJobUpdate: true,
      workerJobDelete: false,
      workerOutboxRead: true,
      workerOutboxInsert: false,
      workerOutboxUpdate: true,
      workerOutboxDelete: false,
      workerIdempotencyRead: false,
      backupRead: true,
      backupWrite: false,
      migrationDdl: true,
      anonBaseWrite: false,
      authenticatedBaseWrite: false,
      applicationFutureObjectRead: false,
      workerFutureObjectRead: false,
    };
    if (JSON.stringify(roleMatrix) !== JSON.stringify(expected)) {
      throw new Error("ROLE_MATRIX_MISMATCH");
    }
    await client.query("set role shipwithali_migration");
    await client.query("drop table operations.__phase3_default_probe");
    await client.query("reset role");
    defaultProbeCreated = false;

    phase = "QUERY_PLANS";
    await client.query("begin");
    await client.query(`
      insert into operations.outbox_events (
        event_id, event_type, schema_version, aggregate_id, aggregate_version,
        payload, correlation_id, occurred_at, available_at
      )
      select ('018f4f7d-1000-7000-8000-' || lpad(to_hex(i), 12, '0'))::uuid,
             'phase3.plan', 1,
             ('018f4f7d-2000-7000-8000-' || lpad(to_hex(i), 12, '0'))::uuid,
             1, '{}'::jsonb, 'phase3-plan',
             '2026-09-22T12:00:00Z'::timestamptz,
             '2026-09-22T12:00:00Z'::timestamptz + (i || ' milliseconds')::interval
        from generate_series(1, 5000) i
      on conflict (event_id) do nothing
    `);
    await client.query(`
      insert into operations.jobs (
        job_id, job_type, payload_version, payload, available_at
      )
      select ('018f4f7d-3000-7000-8000-' || lpad(to_hex(i), 12, '0'))::uuid,
             'phase3.plan', 1, '{}'::jsonb,
             '2026-09-22T12:00:00Z'::timestamptz + (i || ' milliseconds')::interval
        from generate_series(1, 5000) i
      on conflict (job_id) do nothing
    `);
    await client.query("analyze operations.outbox_events");
    await client.query("analyze operations.jobs");
    const outboxPlan = await client.query(`
      explain (format json)
      select event_id from operations.outbox_events
       where completed_at is null
         and available_at <= '2026-09-22T12:00:03Z'::timestamptz
         and (lease_expires_at is null or lease_expires_at <= '2026-09-22T12:00:03Z'::timestamptz)
       order by available_at, event_id limit 25
    `);
    const jobPlan = await client.query(`
      explain (format json)
      select job_id from operations.jobs
       where completed_at is null
         and available_at <= '2026-09-22T12:00:03Z'::timestamptz
         and (status = 'available' or lease_expires_at <= '2026-09-22T12:00:03Z'::timestamptz)
       order by available_at, job_id limit 25
    `);

    await client.query("create schema if not exists phase3_plan");
    await client.query(`
      create table phase3_plan.projects (
        id uuid primary key,
        published_at timestamptz not null,
        title text not null
      )
    `);
    await client.query(
      "create index phase3_plan_projects_published_idx on phase3_plan.projects (published_at desc, id)",
    );
    await client.query(`
      insert into phase3_plan.projects
      select ('018f4f7d-4000-7000-8000-' || lpad(to_hex(i), 12, '0'))::uuid,
             '2026-09-22T12:00:00Z'::timestamptz + (i || ' milliseconds')::interval,
             'project-' || i
        from generate_series(1, 5000) i
    `);
    await client.query(`
      create view public_read.__phase3_plan with (security_barrier = true) as
      select id, published_at, title from phase3_plan.projects
    `);
    await client.query("analyze phase3_plan.projects");
    const publicPlan = await client.query(`
      explain (format json)
      select id, title from public_read.__phase3_plan
       where published_at >= '2026-09-22T12:00:04Z'::timestamptz
       order by published_at desc, id limit 25
    `);

    const plans = {
      outbox: collectIndexes(outboxPlan.rows[0]["QUERY PLAN"][0].Plan),
      jobs: collectIndexes(jobPlan.rows[0]["QUERY PLAN"][0].Plan),
      publicRead: collectIndexes(publicPlan.rows[0]["QUERY PLAN"][0].Plan),
    };
    if (!plans.outbox.includes("outbox_events_due_idx")) {
      throw new Error("OUTBOX_PLAN_MISSING_INDEX");
    }
    if (!plans.jobs.includes("jobs_due_idx")) {
      throw new Error("JOB_PLAN_MISSING_INDEX");
    }
    if (!plans.publicRead.includes("phase3_plan_projects_published_idx")) {
      throw new Error("PUBLIC_READ_PLAN_MISSING_INDEX");
    }
    await client.query("rollback");

    phase = "TYPE_DRIFT";
    execFileSync(
      process.execPath,
      [
        CODEGEN,
        "--dialect",
        "postgres",
        "--url",
        "env(PHASE3_DATABASE_URL)",
        "--default-schema",
        "operations",
        "--include-pattern",
        "operations.*",
        "--date-parser",
        "timestamp",
        "--out-file",
        GENERATED,
        "--verify",
        "--log-level",
        "error",
      ],
      {
        cwd: ROOT,
        env: { ...process.env, PHASE3_DATABASE_URL: connectionString },
        stdio: "ignore",
      },
    );

    return {
      tables: tables.rows.map((row) => row.relname),
      policies: policies.rows.map((row) => ({
        table: row.tablename,
        policy: row.policyname,
        roles: row.roles,
        command: row.cmd,
      })),
      roleMatrix,
      queryPlanIndexes: plans,
      generatedTypeDrift: false,
    };
  } catch (error) {
    if (error instanceof Error && !/^[A-Z0-9_]+$/.test(error.message)) {
      throw new Error(`PHASE3_${phase}_FAILED`);
    }
    throw error;
  } finally {
    try {
      await client.query("rollback");
      if (defaultProbeCreated) {
        await client.query("set role shipwithali_migration");
        await client.query("drop table if exists operations.__phase3_default_probe");
        await client.query("reset role");
      }
    } finally {
      await client.end();
    }
  }
}

async function main() {
  const sourceOnly = process.argv.includes("--source-only");
  const source = sourceVerification();
  if (source.failures.length > 0) {
    for (const failure of source.failures) console.error(`✗ ${failure}`);
    return 1;
  }
  console.log("✓ Phase 3 database architecture and migration sources are confined");
  if (sourceOnly) return 0;

  const connectionString = process.env.PHASE3_DATABASE_URL;
  if (!connectionString) {
    console.error("✗ PHASE3_DATABASE_URL_REQUIRED");
    return 1;
  }
  try {
    const local = await localVerification(connectionString);
    const migrations = source.migrations.map((file) => ({
      file,
      sha256: createHash("sha256")
        .update(readFileSync(join(ROOT, "supabase", "migrations", file)) )
        .digest("hex"),
    }));
    mkdirSync(dirname(EVIDENCE), { recursive: true });
    writeFileSync(
      EVIDENCE,
      `${JSON.stringify(
        {
          ticket: 54,
          parent: 44,
          scope: "phase-3-database-reproducibility-security-and-plans",
          migrations,
          ...local,
          credentialsRecorded: false,
          rawSqlRecorded: false,
        },
        null,
        2,
      )}\n`,
      "utf8",
    );
    console.log("✓ Phase 3 role/RLS matrix, generated types, and query plans passed");
    return 0;
  } catch (error) {
    const code =
      error instanceof Error && /^[A-Z0-9_]+$/.test(error.message)
        ? error.message
        : typeof error?.code === "string" && /^[0-9A-Z]{5}$/.test(error.code)
          ? `POSTGRES_SQLSTATE_${error.code}`
        : "PHASE3_DATABASE_VERIFICATION_FAILED";
    console.error(`✗ ${code}`);
    return 1;
  }
}

process.exitCode = await main();
