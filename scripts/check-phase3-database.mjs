function listFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

function migrationFiles() {
  return readdirSync(join(ROOT, "supabase", "migrations"))
    .filter((file) => /^\d{14}_[a-z0-9_]+\.sql$/.test(file))
    .sort();
}

function sourceVerification() {
  const failures = [];
  const migrations = migrationFiles();
  const migrationText = migrations
    .map((file) => readFileSync(join(ROOT, "supabase", "migrations", file), "utf8"))
    .join("\n")
    .toLowerCase();
  for (const table of TABLES) {
    if (!migrationText.includes(`create table operations.${table}`)) {
      failures.push(`missing operations.${table}`);
    }
    if (!migrationText.includes(`alter table operations.${table} force row level security`)) {
      failures.push(`operations.${table} does not force RLS`);
    }
  }
  if (/create\s+(?:unlogged\s+)?table\s+(?:phase3_test|public_read\.__phase3)/i.test(migrationText)) {
    failures.push("production migrations contain disposable fixture objects");
  }
  if (/security\s+definer/i.test(migrationText)) {
    failures.push("production migrations contain privilege-elevated functions");
  }
  if (!existsSync(GENERATED) || !readFileSync(GENERATED, "utf8").includes("generated by kysely-codegen")) {
    failures.push("generated database types are missing");
  }

  for (const file of listFiles(join(ROOT, "src")).filter((path) => path.endsWith(".ts"))) {
    const path = relative(ROOT, file).split("\\").join("/");
    const content = readFileSync(file, "utf8");
    const adapter = path.includes("/adapters/") || path === "src/bootstrap/composition-root.ts";
    const specifiers = [];
    for (const match of content.matchAll(
      /(?:from\s+|import\s*\(\s*|require\s*\(\s*)["']([^"']+)["']/g,
    )) {
      specifiers.push(match[1]);
    }
    for (const match of content.matchAll(/\bimport\s*["']([^"']+)["']/g)) {
      specifiers.push(match[1]);
    }
    if (/from\s+["'](?:kysely|pg)["']/.test(content) && !adapter) {
      failures.push(`${path} imports a database provider outside adapters/composition`);
    }
    if (/database\.generated(?:\.js)?["']/.test(content) && !path.includes("/adapters/")) {
      failures.push(`${path} imports generated database types outside adapters`);
    }
    if (/\bAsyncLocalStorage\b/.test(content)) {
      failures.push(`${path} uses hidden ambient transaction state`);
    }
    if (/new\s+(?:Pool|Kysely)\s*\(/.test(content) && !adapter) {
      failures.push(`${path} constructs a database provider outside composition/adapters`);
    }
    if (
      specifiers.some((specifier) => /postgres\/runtime(?:\.js)?$/.test(specifier)) &&
      !adapter
    ) {
      failures.push(`${path} imports transaction implementation outside adapters/composition`);
    }
  }

  return { failures, migrations };
}

async function roleAllows(connectionString, role, statement) {
  if (!ROLES.includes(role)) throw new Error("UNKNOWN_ROLE");
  // Credited assertions connect as the role under test: a disposable login
  // with exactly one capability membership connects with its own password and
  // asserts through `set role`. Superuser impersonation is never used, and
  // probe passwords use a closed alphabet so they interpolate safely.
  const admin = new Client({ connectionString });
  await admin.connect();
  const login = `phase3_verify_${process.pid}_${probeCounter++}`;
  const password = randomBytes(24).toString("hex");
  const loginUrl = new URL(connectionString);
  loginUrl.username = login;
  loginUrl.password = password;
  const probe = new Client({ connectionString: loginUrl.toString() });
  let allowed = false;
  try {
    await admin.query(
      `create role "${login}" login password '${password}' nosuperuser nocreatedb nocreaterole noreplication nobypassrls`,
    );
    await admin.query(`grant ${role} to "${login}"`);
    await probe.connect();
    await probe.query("begin");
    await probe.query(`set role ${role}`);
    const identity = await probe.query("select session_user, current_user");
    if (
      identity.rows[0]?.session_user !== login ||
      identity.rows[0]?.current_user !== role
    ) {
      throw new Error("ROLE_ATTRIBUTION_FAILED");
    }
    try {
      await probe.query(statement);
      allowed = true;
    } catch {
      allowed = false;
    }
    await probe.query("rollback");
  } finally {
    await cleanupProbeRole({ admin, probe, login, role });
  }
  return allowed;
}

function collectIndexes(plan) {
  const indexes = [];
  const visit = (node) => {
    if (typeof node?.["Index Name"] === "string") indexes.push(node["Index Name"]);
    for (const child of node?.Plans ?? []) visit(child);
  };
  visit(plan);
  return [...new Set(indexes)].sort();
}

